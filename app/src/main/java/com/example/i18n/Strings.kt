/**
 * 中英双语支持。
 *
 * 设计取舍：**以中文原文作为 key**。
 *
 * - 全项目 5000+ 条中文串，逐个起英文 key 既容易错位，也让 diff 不可读；
 * - 用原文当 key 时，翻译缺失只会退回中文——永远不会出现 "settings.title" 这种
 *   半成品符串跑到界面上；
 * - 迁移是渐进的：新页面直接写 `str.t("原文")`，旧页面保持原样也能跑。
 *
 * 只覆盖界面文案。**数据键不参与翻译**：分类名、书源 id、数据库里的
 * `DEFAULT_CATEGORY` 等都是持久化数据，翻译它们会直接把用户的分类改掉。
 */
enum class AppLanguage(val tag: String) {
    ZH("zh"),
    EN("en");

    companion object {
        fun of(tag: String?): AppLanguage =
            if (tag != null && tag.startsWith("en", ignoreCase = true)) EN else ZH
    }
}

/**
 * 全局语言状态。设置页改它 → 根组合读到 state 变化 → 整个界面立刻换语言，
 * 不需要重建 Activity，也不会把正在读的页面顶掉。
 */
object AppLocale {
    var language by mutableStateOf(AppLanguage.ZH)

    /** 非 Compose 上下文（Toast、通知、日志）取文案用。 */
    fun t(source: String): String = if (language == AppLanguage.EN) EN[source] ?: source else source
}

/**
 * 翻译入口（普通函数，读同一个可观察状态）。
 *
 * 与 `str.t(…)` 的区别只有一个：不用在 Composable 里先取 `val str = rememberStrings()`。
 * 在组合期调用时读的是 `AppLocale.language` 这个快照状态，切语言会正常触发重组。
 *
 * **词表是白名单**：没有条目的字符串原样返回，所以它可以安全地包住"可能是数据"的位置
 * （书名、分类名、文件名），不会把用户数据翻译掉。
 */
fun tr(source: String): String = AppLocale.t(source)

/** 一个语言的文案表。 */
class StringTable(private val language: AppLanguage) {

    fun t(source: String): String = if (language == AppLanguage.EN) EN[source] ?: source else source

    val isEnglish: Boolean get() = language == AppLanguage.EN

    /**
     * 带数字的短句。英文要区分单复数，中文不用，所以这类句子统一走函数，
     * 而不是把 `"$n 本"` 塞进字典。
     */
    fun books(count: Int): String =
        if (!isEnglish) "$count 本" else if (count == 1) "1 book" else "$count books"

    fun chapters(index: Int, total: Int): String =
        if (!isEnglish) "第 $index / $total 章" else "Ch. $index / $total"

    fun readPercent(percent: Int): String =
        if (!isEnglish) "已读 $percent%" else "Read $percent%"

    fun byAuthor(author: String): String = if (!isEnglish) "著  $author" else "by $author"

    fun version(name: String): String = if (!isEnglish) "版本 $name" else "Version $name"

    fun streak(days: Int): String =
        if (!isEnglish) "连续 $days 天" else if (days == 1) "1 day streak" else "$days day streak"

    fun todayMinutes(minutes: Int): String =
        if (!isEnglish) "今日已阅读 $minutes 分钟" else "Read $minutes min today"

    // ── 带插值的界面短句 ────────────────────────────────────────
    // 这些句子不能进字典（`"第 3/140 章"` 这种运行时字符串永远匹配不到 key），
    // 所以统一做成函数：中文拼原样，英文按英文语序拼。

    /** 书架上/详情里的「3/140 章」。 */
    fun chapterCounter(index: Int, total: Int): String =
        if (!isEnglish) "$index/$total 章" else "Ch. $index/$total"

    /** 阅读器顶部「第 3 章」。 */
    fun chapterLabel(index: Int): String = if (!isEnglish) "第 $index 章" else "Chapter $index"

    /** 「第 3 页」/「第 3 / 20 页」。 */
    fun pageLabel(index: Int): String = if (!isEnglish) "第 $index 页" else "Page $index"

    fun pageCounter(index: Int, total: Int): String =
        if (!isEnglish) "第 $index / $total 页" else "Page $index / $total"

    /** 新手引导「第 2 步，共 6 步」。 */
    fun stepCounter(step: Int, total: Int): String =
        if (!isEnglish) "第 $step 步，共 $total 步" else "Step $step of $total"

    /** 图表标题「周一阅读记录：」。 */
    fun dayReadLog(day: String): String = if (!isEnglish) "${day}阅读记录：" else "$day reading log:"

    /** 「本周共 120 分钟」。 */
    fun weekMinutes(minutes: Int): String =
        if (!isEnglish) "本周共 $minutes 分钟" else if (minutes == 1) "1 min this week" else "$minutes min this week"

    /** 休息提醒「已持续阅读 30 分钟，建议远眺片刻！」。 */
    fun restReminder(minutes: Int): String =
        if (!isEnglish) "已持续阅读 $minutes 分钟，建议远眺片刻！"
        else "You've been reading for $minutes min — look into the distance for a moment!"

    /** 「展开全部 12 条」。 */
    fun expandAll(count: Int): String =
        if (!isEnglish) "展开全部 $count 条" else if (count == 1) "Show 1 more" else "Show all $count"

    /** 清空搜索历史确认文案。 */
    fun clearSearchHistory(count: Int): String =
        if (!isEnglish) "将删除全部 $count 条历史搜索词，此操作不可撤销。"
        else if (count == 1) "This deletes your 1 saved search and cannot be undone."
        else "This deletes all $count saved searches and cannot be undone."

    /** 统计页「共 12 小时」。 */
    fun totalOf(value: String): String = if (!isEnglish) "共 $value" else "Total $value"

    /** 「12 项 · 共 34 MB」。 */
    fun itemsOfTotal(items: Int, total: String): String =
        if (!isEnglish) "$items 项 · 共 $total" else "$items items · $total"

    /** 「剩余 3 MB / 共 12 MB」。 */
    fun remainingOfTotal(remaining: String, total: String): String =
        if (!isEnglish) "剩余 $remaining / 共 $total" else "$remaining left of $total"

    /** 「共 240 页」。 */
    fun pagesTotal(count: Int): String =
        if (!isEnglish) "共 $count 页" else if (count == 1) "1 page" else "$count pages"

    // ── 带插值的状态/提示句（第四轮参数化） ─────────────────────

    fun sourcesReadable(count: Int): String =
        if (!isEnglish) "$count 个源可读" else if (count == 1) "1 source" else "$count sources"

    fun filterCount(count: Int): String =
        if (!isEnglish) "当前筛选 $count 本"
        else if (count == 1) "1 filtered result" else "$count filtered results"

    fun titleDisabled(title: String): String =
        if (!isEnglish) "$title · 已停用" else "$title · disabled"

    fun sourcesSubmitted(count: Int): String =
        if (!isEnglish) "已提交 $count 个书源"
        else if (count == 1) "1 source submitted" else "$count sources submitted"

    fun filesTotal(count: Int): String =
        if (!isEnglish) "共 $count 个文件" else if (count == 1) "1 file" else "$count files"

    fun downloadChapters(count: Int, sizeMb: String): String =
        if (!isEnglish) "下载 $count 话 · 约 $sizeMb MB"
        else if (count == 1) "Download 1 chapter · about $sizeMb MB"
        else "Download $count chapters · about $sizeMb MB"

    fun categoryName(name: String): String = if (!isEnglish) "分类 $name" else "Category $name"

    fun categorySelected(name: String): String =
        if (!isEnglish) "分类 $name，已选中" else "Category $name, selected"

    fun categoryLocked(name: String): String =
        if (!isEnglish) "分类『$name』已锁定" else "The \"$name\" category is locked"

    fun categoryCreated(name: String): String =
        if (!isEnglish) "已创建分类「$name」" else "Category \"$name\" created"

    fun categoryEmpty(name: String): String =
        if (!isEnglish) "在分类『$name』下还没有任何图书哦。您可以点击下方按钮导入新书到该分类！"
        else "Nothing in \"$name\" yet. Tap the button below to import a book here!"

    fun favouritesAdded(count: Int): String =
        if (!isEnglish) "已加入我喜欢的 $count 本"
        else if (count == 1) "Added 1 book to favourites" else "Added $count books to favourites"

    fun favouritesAddedPartial(added: Int, skipped: Int): String =
        if (!isEnglish) "已喜欢 $added 本，$skipped 本无来源已跳过"
        else "Liked $added, skipped $skipped without a source"

    fun comicIdLabel(id: String): String = if (!isEnglish) "编号：$id" else "ID: $id"

    fun highlightOf(name: String): String = if (!isEnglish) "神回 · $name" else "Highlight · $name"

    fun closeNamed(title: String): String = if (!isEnglish) "关闭$title" else "Close $title"

    fun yearLabel(year: String): String = if (!isEnglish) "${year}年" else year

    fun minutesValue(value: String): String =
        if (!isEnglish) "$value 分钟" else if (value == "1") "1 min" else "$value min"

    fun dailyAverage(average: String, previousName: String, previousText: String): String =
        if (!isEnglish) "日均 $average · 较$previousName $previousText"
        else "Daily $average · $previousText vs $previousName"

    fun migrateIntro(title: String): String =
        if (!isEnglish) "《$title》\n选择来源后，收藏、阅读进度与已读状态会按章节顺序迁移过去。"
        else "$title\nPick a source — favourites, progress and read state migrate chapter by chapter."

    fun expandRest(count: Int): String =
        if (!isEnglish) "展开其余 $count 个" else if (count == 1) "Show 1 more" else "Show $count more"

    fun switchedTo(node: String): String = if (!isEnglish) "已切换到 $node" else "Switched to $node"

    fun homeHttpCode(code: Int): String =
        if (!isEnglish) "首页返回 HTTP $code" else "Home page returned HTTP $code"
}

