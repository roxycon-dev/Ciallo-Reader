/**
 * 大数字的紧凑写法：中文用 亿 / 万，英文用 M / k。
 * 这类单位后缀是语言相关的，不能当成普通词条塞进字典（`%.1f亿` 含有格式符）。
 */
fun compactCount(value: Long?): String {
    if (value == null) return table().t("未提供")
    return if (AppLocale.language == AppLanguage.EN) {
        when {
            value >= 1_000_000 -> "%.1fM".format(java.util.Locale.US, value / 1_000_000.0)
            value >= 1_000 -> "%.1fk".format(java.util.Locale.US, value / 1_000.0)
            else -> value.toString()
        }
    } else {
        when {
            value >= 100_000_000 -> "%.1f亿".format(java.util.Locale.CHINA, value / 100_000_000.0)
            value >= 10_000 -> "%.1f万".format(java.util.Locale.CHINA, value / 10_000.0)
            else -> value.toString()
        }
    }
}
